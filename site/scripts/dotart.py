"""Draw the landing's pictures as smooth greyscale scenes, then sample them into the dot grid of the Omarchy hands.

Each cell becomes a full dot (#), a small shading dot (+), a crimson dot (x) or nothing, by the brightness under it,
like the halftone of the hands. Writes lib/landing/pictures.ts.  Run: python3 scripts/dotart.py
"""
import math
from pathlib import Path
from PIL import Image, ImageDraw

HERE = Path(__file__).resolve().parent.parent
CW, CH = 10, 18.6          # a cell, as in the hands: twice as tall as wide
S = 4                       # supersampling


def canvas(cols, rows):
    w, h = int(cols * CW * S), int(rows * CH * S)
    lum = Image.new("L", (w, h), 0)
    hot = Image.new("L", (w, h), 0)
    return lum, hot, ImageDraw.Draw(lum), ImageDraw.Draw(hot), w, h


Z = 1.4                     # dots per design cell: the pictures are drawn on a 50x13 grid and sampled finer


def sample(lum, hot, cols, rows):
    out = []
    cw, ch = CW * S / Z, CH * S / Z
    for r in range(round(rows * Z)):
        row = ""
        for c in range(round(cols * Z)):
            box = (int(c * cw), int(r * ch), int((c + 1) * cw), int((r + 1) * ch))
            v = sum(lum.crop(box).getdata()) / ((box[2] - box[0]) * (box[3] - box[1]) * 255)
            h = sum(hot.crop(box).getdata()) / ((box[2] - box[0]) * (box[3] - box[1]) * 255)
            row += "x" if h > 0.35 else "#" if v > 0.55 else "+" if v > 0.16 else " "
        out.append(row)
    return out


def cell(x, y):
    """Cell coordinates to canvas pixels."""
    return x * CW * S, y * CH * S


def rect(d, x0, y0, x1, y1, fill):
    d.rectangle((*cell(x0, y0), *cell(x1, y1)), fill=fill)


def oval(d, cx, cy, rx, ry, fill):
    (x0, y0), (x1, y1) = cell(cx - rx, cy - ry), cell(cx + rx, cy + ry)
    d.ellipse((x0, y0, x1, y1), fill=fill)


def gpu():
    cols, rows = 50, 13
    lum, hot, d, dh, w, h = canvas(cols, rows)
    rect(d, 1, 0, 49, 10, 255)                       # the shroud, solid
    for cx in (14, 36):
        oval(d, cx, 5, 10, 4.6, 0)                   # the fan opening
        oval(d, cx, 5, 8.6, 3.8, 60)                 # behind the blades, in shading
        oval(d, cx, 5, 6.4, 2.9, 255)                # a bright ring of blades
        oval(d, cx, 5, 4.6, 2.05, 60)
        oval(d, cx, 5, 2.2, 1.0, 0)
        oval(dh, cx, 5, 1.6, 0.75, 255)              # the hub, lit
    rect(d, 6, 11, 30, 12.6, 100)                    # the edge connector, in shading
    rect(d, 31.5, 11, 42, 12.6, 100)
    return sample(lum, hot, cols, rows)


def net():
    cols, rows = 50, 13
    lum, hot, d, dh, w, h = canvas(cols, rows)
    layers, xs = [3, 4, 3], [6, 25, 44]
    pts = [[(xs[i], rows * (j + 1) / (n + 1)) for j in range(n)] for i, n in enumerate(layers)]
    lit = [(0, 1), (1, 2), (2, 1)]
    for i in range(len(pts) - 1):                    # every weight, faint
        for a in pts[i]:
            for b in pts[i + 1]:
                d.line((cell(*a), cell(*b)), fill=80, width=int(0.6 * CW * S))
    for i in range(len(lit) - 1):                    # the path one token takes, bright
        a, b = pts[lit[i][0]][lit[i][1]], pts[lit[i + 1][0]][lit[i + 1][1]]
        d.line((cell(*a), cell(*b)), fill=255, width=int(0.5 * CH * S))
    for i, layer in enumerate(pts):
        for j, (x, y) in enumerate(layer):
            oval(d, x, y, 2.4, 1.1, 255)
            if (i, j) in lit:
                oval(dh, x, y, 2.4, 1.1, 255) if i == len(pts) - 1 else None
    return sample(lum, hot, cols, rows)


def term():
    cols, rows = 50, 13
    lum, hot, d, dh, w, h = canvas(cols, rows)
    rect(d, 1, 0, 49, 13, 255)                       # the window
    rect(d, 2.2, 2, 47.8, 12, 0)                     # its body
    for k, x in enumerate((4.5, 8.5, 12.5)):         # the title bar's three lights, the first one live
        oval(d, x, 1, 1.3, 0.55, 0)
        if k == 0:
            oval(dh, x, 1, 1.0, 0.45, 255)
    d.polygon([cell(5, 3.6), cell(11, 6.4), cell(5, 9.2), cell(5, 7.9), cell(8.6, 6.4), cell(5, 4.9)], fill=255)  # the prompt
    for k, x1 in enumerate((40, 33, 37)):            # what the agent wrote
        rect(d, 16, 3.6 + 2.4 * k, x1, 4.4 + 2.4 * k, 120)
    rect(dh, 16, 9.6, 19, 10.6, 255)                 # the cursor
    return sample(lum, hot, cols, rows)


def main():
    out = ["// Generated by scripts/dotart.py: smooth scenes sampled into the dot grid of the hands. Do not edit by hand.",
           "// # dot, + shading dot, x crimson, space empty (see components/Dots.tsx).", ""]
    for name, doc, f in (("GPU", "Your graphics card: the shroud, two fans, the slot.", gpu),
                         ("NET", "A model: layers of weights, one path lit.", net),
                         ("TERMINAL", "Your agent: a terminal with a live cursor.", term)):
        rows = f()
        out.append(f"/** {doc} */")
        out.append(f"export const {name} = [")
        out += [f'  "{r}",' for r in rows]
        out.append("];")
        out.append("")
        print(name); print("\n".join(rows)); print()
    (HERE / "lib" / "landing" / "pictures.ts").write_text("\n".join(out))


main()
